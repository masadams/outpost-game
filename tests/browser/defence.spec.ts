import { expect } from '@playwright/test';
import { test } from './game';
import { WORLD } from '../../src/sim/config';

test('builds and controls a turret, defends an opt-in drill, then saves the resolved world', async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); const hud = page.locator('#hud'), panel = page.locator('.defence-panel');
  await expect(panel).toHaveAttribute('data-threats', '0'); await expect(panel).toHaveAttribute('data-wave', '0');
  await page.keyboard.press('f'); await page.keyboard.down('d');
  await expect.poll(async () => Number(await hud.getAttribute('data-surface-angle')) * WORLD.radius, { timeout: 10000, intervals: [100] }).toBeGreaterThan(96);
  await page.keyboard.up('d'); await page.waitForTimeout(450);
  await page.keyboard.press('b'); await page.keyboard.press('Enter'); await expect(hud).toHaveAttribute('data-buildings', '1');
  await page.keyboard.press('t'); await page.keyboard.press('7'); await page.keyboard.press('Enter'); await expect(hud).toHaveAttribute('data-buildings', '2');
  await page.keyboard.press('b'); await page.keyboard.down('d');
  await expect.poll(async () => Number(await hud.getAttribute('data-surface-angle')) * WORLD.radius, { timeout: 8000, intervals: [100] }).toBeGreaterThan(145);
  await page.keyboard.up('d'); await page.waitForTimeout(450);
  await page.getByRole('button', { name: 'Control turret [E]', exact: true }).click();
  await expect(panel).toHaveAttribute('data-controlled', '2');
  const position = await hud.getAttribute('data-surface-angle');
  await page.keyboard.down('d');
  await expect.poll(async () => Number(await page.locator('.machine').getAttribute('data-aim'))).toBeGreaterThan(0.15);
  await page.keyboard.up('d'); await page.keyboard.down('Space');
  await expect.poll(async () => Number(await panel.getAttribute('data-shots'))).toBeGreaterThan(0);
  await page.keyboard.up('Space'); await expect(panel).toHaveAttribute('data-controlled', '2'); expect(await hud.getAttribute('data-surface-angle')).toBe(position);
  await expect(hud).toHaveAttribute('data-grounded', 'true');
  await page.keyboard.press('g'); await page.keyboard.press('e'); await expect(panel).toHaveAttribute('data-controlled', '');
  await expect(page.getByRole('button', { name: 'Auto defence [G]: on', exact: true })).toBeAttached();
  await page.keyboard.press('n'); await expect(panel).toHaveAttribute('data-wave', '1'); await expect(panel).toHaveAttribute('data-threats', '1');
  await expect(page.locator('#threat-alert')).toContainText('INCOMING');
  await page.keyboard.press('p'); await expect(hud).toHaveAttribute('data-state', 'paused');
  const frozenShots = await panel.getAttribute('data-shots'), frozenOxygen = await hud.getAttribute('data-oxygen');
  await page.mouse.move(640, 350); for (let i = 0; i < 5; i++) await page.mouse.wheel(0, 300);
  await page.waitForTimeout(1300);
  expect(await panel.getAttribute('data-shots')).toBe(frozenShots); expect(await hud.getAttribute('data-oxygen')).toBe(frozenOxygen);
  await page.screenshot({ path: 'docs/screenshots/planetary-defence.png' });
  await page.keyboard.press('p');
  await expect.poll(async () => Number(await panel.getAttribute('data-intercepted')), { timeout: 25000, intervals: [200] }).toBeGreaterThanOrEqual(3);
  await expect(panel).toHaveAttribute('data-threats', '0'); await expect(panel).toHaveAttribute('data-impacts', '0'); await expect(hud).toHaveAttribute('data-objectives', /defence/);
  await page.keyboard.press('k'); await expect(page.locator('.status')).toContainText('CHECKPOINT SAVED');
  await page.reload(); await expect(hud).toHaveAttribute('data-state', 'paused');
  await expect(hud).toHaveAttribute('data-buildings', '2'); await expect(panel).toHaveAttribute('data-wave', '1');
  await expect(panel).toHaveAttribute('data-intercepted', '3'); await expect(panel).toHaveAttribute('data-threats', '0'); await expect(hud).toHaveAttribute('data-objectives', /defence/);
  expect(errors).toEqual([]);
});
